/**
 * Turn one Claude Code session file into the instrument's `Turn[]`.
 *
 * A session is stored as JSON Lines at
 * `~/.claude/projects/<encoded-cwd>/<session-id>.jsonl`. Each line is one event.
 * Only two event types carry conversation text:
 *
 *   - `type: "user"`      — a message from the person, UNLESS it is a tool
 *                           result, a meta / compact-summary injection, or an
 *                           empty slash-command wrapper.
 *   - `type: "assistant"` — the model's reply; we keep its `text` blocks and
 *                           drop `thinking` and `tool_use`.
 *
 * Everything else (environment snapshots, file-history deltas, titles, mode
 * changes, sidechain / subagent turns) is ignored. Consecutive turns from the
 * same role are merged. The result is what `scoreTranscript` expects.
 *
 * The filtering here is deliberately visible and conservative — see
 * `docs/INSTRUMENT_CLI.md`. It reads the person's half of the conversation and
 * nothing else.
 */

import type { Turn } from "../lib/instrument/types.ts";

interface RawTurn {
  role: "user" | "assistant";
  text: string;
}

/** A `<tag>...</tag>` block the CLI strips out of user text, plus a few
 *  bare markers Claude Code inserts. Matched case-sensitively, across lines. */
const STRIP_BLOCKS: RegExp[] = [
  /<system-reminder>[\s\S]*?<\/system-reminder>/g,
  /<command-name>[\s\S]*?<\/command-name>/g,
  /<command-message>[\s\S]*?<\/command-message>/g,
  /<command-args>[\s\S]*?<\/command-args>/g,
  /<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g,
  /<user-prompt-submit-hook>[\s\S]*?<\/user-prompt-submit-hook>/g,
];

const STRIP_LINES: RegExp[] = [
  /^\s*\[Request interrupted by user[^\]]*\]\s*$/gm,
  /^\s*Caveat: The messages below were generated by the user while running local commands\..*$/gm,
];

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Pull the plain text out of a `message.content` that is a string or an array
 *  of blocks. Returns `null` when the content is a tool result (or otherwise
 *  carries no readable text). */
function contentText(content: unknown): string | null {
  if (typeof content === "string") return content;
  if (!Array.isArray(content)) return null;

  const parts: string[] = [];
  for (const block of content) {
    if (!isRecord(block)) continue;
    if (block.type === "tool_result") return null;
    if (block.type === "text" && typeof block.text === "string") {
      parts.push(block.text);
    }
  }
  return parts.length > 0 ? parts.join("\n") : null;
}

/** Remove the wrappers Claude Code injects around a typed message, then
 *  collapse the leftover whitespace. Exported so the session picker labels
 *  sessions with the same cleaned text this parser would keep. */
export function cleanUserText(text: string): string {
  let out = text;
  for (const re of STRIP_BLOCKS) out = out.replace(re, " ");
  for (const re of STRIP_LINES) out = out.replace(re, " ");
  return out.replace(/\s+/g, " ").trim();
}

function collapse(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

/** Parse the file text into raw `{ role, text }` turns, in order, before merge. */
function rawTurns(fileText: string): RawTurn[] {
  const turns: RawTurn[] = [];

  for (const line of fileText.split("\n")) {
    const trimmed = line.trim();
    if (trimmed === "") continue;

    let entry: unknown;
    try {
      entry = JSON.parse(trimmed);
    } catch {
      continue; // a torn last line, etc. — skip it, don't fail the session
    }
    if (!isRecord(entry)) continue;
    if (entry.isSidechain === true) continue; // subagent conversation

    const type = entry.type;
    const message = isRecord(entry.message) ? entry.message : null;

    if (type === "user") {
      if (entry.isMeta === true || entry.isCompactSummary === true) continue;
      if ("toolUseResult" in entry) continue; // tool result echoed as a user turn
      const raw = contentText(message?.content);
      if (raw === null) continue;
      const text = cleanUserText(raw);
      if (text === "") continue; // was pure wrapper / interrupt marker
      turns.push({ role: "user", text });
      continue;
    }

    if (type === "assistant") {
      const raw = contentText(message?.content);
      if (raw === null) continue;
      const text = collapse(raw);
      if (text === "") continue; // thinking-only / tool-call-only reply
      turns.push({ role: "assistant", text });
    }
  }

  return turns;
}

/** Merge consecutive same-role turns and assign a contiguous `index`. */
function mergeAndIndex(raw: RawTurn[]): Turn[] {
  const merged: RawTurn[] = [];
  for (const turn of raw) {
    const last = merged[merged.length - 1];
    if (last && last.role === turn.role) {
      last.text = `${last.text}\n\n${turn.text}`;
    } else {
      merged.push({ ...turn });
    }
  }
  return merged.map((turn, index) => ({
    role: turn.role,
    text: turn.text,
    index,
  }));
}

/**
 * Parse a Claude Code `.jsonl` session into `Turn[]`.
 *
 * @param fileText the full contents of one session file.
 */
export function parseSession(fileText: string): Turn[] {
  return mergeAndIndex(rawTurns(fileText));
}
